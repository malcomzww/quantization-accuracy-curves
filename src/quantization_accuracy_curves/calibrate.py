"""Calibration corpora and the importance matrices they produce.

An imatrix is one number per input feature of one weight matrix: the mean
squared activation that feature saw while the model read a calibration
corpus. The quantiser spends its limited bit budget where that number is
large. So the imatrix is a *summary of the calibration text*, and two corpora
that excite different features produce two different quantised models from
identical starting weights.

That is the mechanism this repository measures. Everything here exists to
make it observable: fixed corpora so the experiment is deterministic, a
forward hook to collect the statistic, and a cosine comparison so the
divergence between two calibration sets can be reported before any
perplexity is computed.

Corpora are vendored inline rather than downloaded. Three reasons, in order
of importance: the results file is regenerated by CI and byte-compared, so a
dataset that reorders or revises upstream would break the build; a fresh
clone must work offline; and a reader can see exactly what the model was
calibrated on without fetching anything. The cost is that these are small,
hand-assembled samples rather than corpus-scale text, which is stated plainly
in the Limitations section of the README.
"""

from __future__ import annotations

from dataclasses import dataclass

