@dataclass(frozen=True)
class Corpus:
    """A named block of calibration text.

    ``description`` is carried through to the results file so a reader can
    tell what distinction a spread number is actually measuring, rather than
    seeing two opaque labels.
    """

    name: str
    description: str
    text: str

    def __str__(self) -> str:  # pragma: no cover - trivial
        return self.name


CORPORA: tuple[Corpus, ...] = (
    Corpus("encyclopedic", "Wikipedia-style expository prose", _ENCYCLOPEDIC),
    Corpus("code", "Python, SQL and JavaScript source", _CODE),
    Corpus("chat", "Instruction-following dialogue turns", _CHAT),
)

CORPORA_BY_NAME: dict[str, Corpus] = {c.name: c for c in CORPORA}

EVAL_CORPUS = Corpus("held-out", "Encyclopedic prose, disjoint from all calibration sets", _EVAL)


# --- importance matrices ----------------------------------------------


def importance_from_activations(activations: list) -> dict:
    """Reduce collected activation batches to one importance vector per layer.

    The statistic is the mean of the squared activation over every token seen,
    per input feature. This is what llama.cpp's ``llama-imatrix`` computes,
    and the reason it is squared rather than absolute is that the quantiser
    minimises a squared reconstruction error -- the weight and the objective
    have to be in the same units or the weighting is arbitrary.

    ``activations`` is a list of ``(name, sum_sq, count)`` triples, summed
    across batches by the caller so nothing large is retained.
    """
    out: dict[str, object] = {}
    for name, sum_sq, count in activations:
        if count <= 0:
            raise ValueError(f"no tokens observed for {name}")
        out[name] = sum_sq / count
    return out


def cosine_similarity(a, b) -> float:
    """Cosine between two importance vectors.

    Reported instead of a raw distance because imatrix magnitude is arbitrary
    -- the quantiser only uses the vector's *shape*, since scaling every
    weight by the same constant cannot change which feature is relatively
    more important. Cosine is invariant to exactly that scaling, so it
    isolates the part of the difference that can actually affect the output.

    Returns a value in [-1, 1]; activation energies are non-negative so in
    practice it lands in [0, 1].
    """
    import numpy as np

    x = np.asarray(a, dtype=np.float64).ravel()
    y = np.asarray(b, dtype=np.float64).ravel()
    if x.shape != y.shape:
        raise ValueError(f"importance vectors differ in shape: {x.shape} vs {y.shape}")
    nx, ny = np.linalg.norm(x), np.linalg.norm(y)
    if nx == 0 or ny == 0:
        raise ValueError("cannot take cosine of a zero importance vector")
    return float(np.dot(x, y) / (nx * ny))
